pub struct MagicCardEntry {
    card_name: &'static str,
    mana_cost: Vec<MagicManaCost>,
    supertype: MagicSupertype,
    typeline: Vec<MagicTypeLine>,
    expansion: MagicExpansion,
    rarity: MagicRarity,
    keyword_abilities: Vec<MagicKeywordAbility>,
    keyword_actions: Vec<MagicKeywordAction>,
    text_box: Vec<&'static str>,
    power_toughness: Option<(i32, i32)>,
    loyalty: Option<i32>,
    defense: Option<i32>,
    hand_modifier: Option<i32>,
    life_modifier: Option<i32>,
    collector_number: u32,
}

impl MagicCardEntry {
    pub fn new(
        card_name: &'static str,
        mana_cost: Vec<MagicManaCost>,
        supertype: MagicSupertype,
        typeline: Vec<MagicTypeLine>,
        expansion: MagicExpansion,
        rarity: MagicRarity,
        keyword_abilities: Vec<MagicKeywordAbility>,
        keyword_actions: Vec<MagicKeywordAction>,
        text_box: Vec<&'static str>,
        power_toughness: Option<(i32, i32)>,
        loyalty: Option<i32>,
        defense: Option<i32>,
        hand_modifier: Option<i32>,
        life_modifier: Option<i32>,
        collector_number: u32,
    ) -> Self {
        MagicCardEntry {
            card_name,
            mana_cost,
            supertype,
            typeline,
            expansion,
            rarity,
            keyword_abilities,
            keyword_actions,
            text_box,
            power_toughness,
            loyalty,
            defense,
            hand_modifier,
            life_modifier,
            collector_number,
        }
    }
}

